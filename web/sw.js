/**
 * Offline shell. Cache-first for the app bundle, network-first for the seed
 * file (it is data, and a stale copy would silently import old cards).
 *
 * Bump CACHE on every release: without it, installed clients keep the old
 * shell until the browser decides to evict it.
 */

const CACHE = "mist-v2";
// sw.js is deliberately absent: the browser fetches the worker script outside
// this cache, so precaching it wastes quota and makes "is everything cached?"
// checks read as failures.
const SHELL = [
  "./",
  "./index.html",
  "./app.js",
  "./core.js",
  "./store.js",
  "./manifest.webmanifest",
  "./icon.svg",
  "./icon-maskable.svg",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  if (request.url.endsWith("seed.json")) {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy));
          return response;
        })
        .catch(() => caches.match(request))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then(
      (cached) =>
        cached ||
        fetch(request).then((response) => {
          if (response.ok && new URL(request.url).origin === self.location.origin) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
    )
  );
});
